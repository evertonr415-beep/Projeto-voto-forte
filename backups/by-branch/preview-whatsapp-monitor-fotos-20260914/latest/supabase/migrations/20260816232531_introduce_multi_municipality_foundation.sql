create table if not exists public.vf_municipalities (
  id bigint generated by default as identity primary key,
  name text not null,
  state text not null default 'PR',
  ibge_code text,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  created_by uuid,
  constraint vf_municipalities_name_state_unique unique (name, state)
);

alter table public.vf_municipalities enable row level security;

drop policy if exists vf_municipalities_select on public.vf_municipalities;
create policy vf_municipalities_select on public.vf_municipalities
for select to anon, authenticated
using (status = 'active');

insert into public.vf_municipalities(name,state,status)
values ('Arapongas','PR','active')
on conflict (name,state) do update set status='active';

create or replace function private.vf_default_municipality_id()
returns bigint
language sql
stable
set search_path = ''
as $$
  select id from public.vf_municipalities
  where name='Arapongas' and state='PR'
  order by id limit 1;
$$;

create table if not exists public.vf_user_municipalities (
  user_id bigint not null references public.vf_users(id) on delete cascade,
  municipality_id bigint not null references public.vf_municipalities(id) on delete cascade,
  access_role text not null check (access_role in ('adm','master','lideranca','liderado','eleitor')),
  status text not null default 'active' check (status in ('active','blocked')),
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (user_id, municipality_id)
);

alter table public.vf_user_municipalities enable row level security;

drop policy if exists vf_user_municipalities_select on public.vf_user_municipalities;
create policy vf_user_municipalities_select on public.vf_user_municipalities
for select to authenticated
using (
  user_id in (select id from public.vf_users where auth_user_id = (select auth.uid()))
  or (select private.vf_is_adm())
);

insert into public.vf_user_municipalities(user_id, municipality_id, access_role, status, is_default)
select u.id, private.vf_default_municipality_id(), u.access_role, u.status, true
from public.vf_users u
on conflict (user_id, municipality_id) do update
set access_role=excluded.access_role, status=excluded.status, is_default=true;


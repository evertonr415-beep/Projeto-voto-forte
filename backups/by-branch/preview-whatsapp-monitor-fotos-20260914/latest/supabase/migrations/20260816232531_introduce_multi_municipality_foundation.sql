create or replace function private.vf_register_signup_request_internal(p_municipality_name text, p_state text default 'PR')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := (select auth.uid());
  au auth.users;
  req public.vf_signup_requests;
  requested_name text := trim(coalesce(p_municipality_name,''));
  requested_state text := upper(trim(coalesce(p_state,'PR')));
begin
  if uid is null then raise exception 'Não autenticado' using errcode='42501'; end if;
  select * into au from auth.users where id=uid;
  if au.id is null then raise exception 'Conta Auth não encontrada' using errcode='42501'; end if;
  if au.email_confirmed_at is null then raise exception 'Confirme seu e-mail antes de solicitar acesso'; end if;
  if requested_name='' or requested_state='' then raise exception 'Município obrigatório'; end if;
  if exists (select 1 from public.vf_users where auth_user_id=uid) then
    return jsonb_build_object('status','already_active');
  end if;
  if exists (select 1 from public.vf_user_invitations where lower(email)=lower(coalesce(au.email,'')) and status='pending' and expires_at>now()) then
    return jsonb_build_object('status','invited');
  end if;
  insert into public.vf_signup_requests(auth_user_id,email,name,municipality_name,state,status)
  values(uid, lower(trim(coalesce(au.email,''))), trim(coalesce(au.raw_user_meta_data->>'name','Usuário')), requested_name, requested_state, 'pending')
  on conflict (auth_user_id) do update set
    municipality_name=excluded.municipality_name,
    state=excluded.state,
    name=excluded.name,
    email=excluded.email,
    status=case when public.vf_signup_requests.status='approved' then public.vf_signup_requests.status else 'pending' end,
    requested_at=case when public.vf_signup_requests.status='approved' then public.vf_signup_requests.requested_at else now() end
  returning * into req;
  return jsonb_build_object('id',req.id,'status',req.status,'municipalityName',req.municipality_name,'state',req.state);
end;
$$;

create or replace function public.vf_register_signup_request(p_municipality_name text, p_state text default 'PR')
returns jsonb
language sql
set search_path=''
as $$ select private.vf_register_signup_request_internal(p_municipality_name,p_state); $$;

revoke all on function public.vf_register_signup_request(text,text) from public, anon;
grant execute on function public.vf_register_signup_request(text,text) to authenticated;

create or replace function private.vf_my_municipalities_internal()
returns jsonb
language plpgsql
security definer
stable
set search_path=''
as $$
declare uid uuid := (select auth.uid());
begin
  if uid is null then raise exception 'Não autenticado' using errcode='42501'; end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'id',m.id,'name',m.name,'state',m.state,'accessRole',um.access_role,
      'status',um.status,'isDefault',um.is_default
    ) order by um.is_default desc,m.name)
    from public.vf_users u
    join public.vf_user_municipalities um on um.user_id=u.id
    join public.vf_municipalities m on m.id=um.municipality_id
    where u.auth_user_id=uid and um.status='active' and m.status='active'
  ),'[]'::jsonb);
end;
$$;

create or replace function public.vf_my_municipalities()
returns jsonb
language sql stable set search_path=''
as $$ select private.vf_my_municipalities_internal(); $$;
revoke all on function public.vf_my_municipalities() from public, anon;
grant execute on function public.vf_my_municipalities() to authenticated;

